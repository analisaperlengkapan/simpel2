/// Create penghapusan BMN request
#[derive(Debug, Clone, Serialize, Deserialize, Validate)]
pub struct CreatePenghapusanBmnRequest {
    pub satker_id: Uuid,
    pub asset_id: Uuid,
    pub kode_barang: String,
    #[validate(length(min = 1, max = 255))]
    pub nama_barang: String,
    #[validate(length(min = 1, max = 50))]
    pub nup: String,
    pub tanggal_penghapusan: NaiveDate,
    #[validate(length(min = 10, max = 1000))]
    pub alasan: String,
    #[validate(length(min = 1, max = 100))]
    pub metode_penghapusan: String,
    pub nilai_perolehan: Option<f64>,
    // Lampiran persyaratan (required)
    #[validate(length(min = 1, message = "Lampiran persyaratan wajib dilampirkan"))]
    pub lampiran_persyaratan: String,
    pub catatan_operator: Option<String>,
    /// V029 (Fase 1.9): Kewenangan penetap SK — 'PUSAT' atau 'WILAYAH'.
    /// Default 'PUSAT' (backward compat). Setelah dipilih, workflow
    /// branching ditentukan di service: WILAYAH = SubmitWilayah →
    /// KonsepSKWilayahGenerated (skip Pusat); PUSAT = jalur normal.
    #[serde(default = "default_kewenangan")]
    pub kewenangan_penetap_sk: String,
    /// Label jabatan penetap (cth: "Kepala Kejaksaan Tinggi DKI Jakarta").
    /// Optional; jika None server isi default berdasarkan kewenangan.
    pub penetap_sk_jabatan: Option<String>,
    /// V036 (Fase 2.8): daftar item BMN multi-item. Bila kosong/None, service
    /// fallback ke item tunggal dari kolom kode_barang/nama_barang/nup di atas
    /// (backward compat). Item pertama menjadi "item utama" tabel induk.
    #[serde(default)]
    pub items: Vec<CreatePenghapusanBmnItemRequest>,
}

