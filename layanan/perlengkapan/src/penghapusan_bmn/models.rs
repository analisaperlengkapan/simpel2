// ============================================================================
// Penghapusan BMN Models
// Description: Data models for Usulan SK Penghapusan BMN workflow
// Requirements: REQ-W001
//
// Flow:
//   Draft(4000) → SubmitWilayah(4001) → SubmitPusat(4003) → VerifikasiPusat(4004) →
//   KonsepSKGenerated(4005) → SKSigned(4006) → Completed(4007)
//   Validator Wilayah can return: ReturnedToOperator(4002)
//   Validator Pusat can reject: Rejected(4008)
// ============================================================================

use chrono::{DateTime, NaiveDate, Utc};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use uuid::Uuid;
use validator::Validate;

/// Workflow status codes for Usulan SK Penghapusan BMN
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[repr(i32)]
#[derive(Default)]
pub enum PenghapusanBmnStatus {
    /// Draft by operator satker
    #[default]
    Draft = 4000,
    /// Submitted to Validator Wilayah
    SubmitWilayah = 4001,
    /// Returned to Operator by Validator Wilayah
    ReturnedToOperator = 4002,
    /// Forwarded to Validator Pusat by Validator Wilayah (kewenangan=PUSAT)
    SubmitPusat = 4003,
    /// Validator Pusat verifying
    VerifikasiPusat = 4004,
    /// Konsep SK generated by Validator Pusat
    KonsepSKGenerated = 4005,
    /// SK signed by Pusat (Jaksa Agung Muda Pembinaan) and PDF uploaded
    SKSigned = 4006,
    /// Process completed
    Completed = 4007,
    /// Rejected by Validator Pusat
    Rejected = 4008,
    /// V029 (Fase 1.9): Konsep SK generated by Validator Wilayah utk
    /// kewenangan=WILAYAH (mewakili Kepala Kejaksaan Tinggi).
    KonsepSKWilayahGenerated = 4010,
    /// V029 (Fase 1.9): SK signed by Kepala Kejati dan PDF uploaded.
    SKSignedWilayah = 4011,
}

impl PenghapusanBmnStatus {
    pub fn from_code(code: i32) -> Option<Self> {
        match code {
            4000 => Some(Self::Draft),
            4001 => Some(Self::SubmitWilayah),
            4002 => Some(Self::ReturnedToOperator),
            4003 => Some(Self::SubmitPusat),
            4004 => Some(Self::VerifikasiPusat),
            4005 => Some(Self::KonsepSKGenerated),
            4006 => Some(Self::SKSigned),
            4007 => Some(Self::Completed),
            4008 => Some(Self::Rejected),
            4010 => Some(Self::KonsepSKWilayahGenerated),
            4011 => Some(Self::SKSignedWilayah),
            _ => None,
        }
    }

    pub fn to_code(self) -> i32 {
        self as i32
    }

    pub fn label(&self) -> &'static str {
        match self {
            Self::Draft => "Draft",
            Self::SubmitWilayah => "Diajukan ke Validator Wilayah",
            Self::ReturnedToOperator => "Dikembalikan ke Operator",
            Self::SubmitPusat => "Diajukan ke Validator Pusat",
            Self::VerifikasiPusat => "Verifikasi Pusat",
            Self::KonsepSKGenerated => "Konsep SK Digenerate (Pusat)",
            Self::SKSigned => "SK Ditandatangani (Pusat)",
            Self::Completed => "Selesai",
            Self::Rejected => "Ditolak",
            Self::KonsepSKWilayahGenerated => "Konsep SK Digenerate (Wilayah)",
            Self::SKSignedWilayah => "SK Ditandatangani (Wilayah)",
        }
    }

    pub fn to_state_name(&self) -> &'static str {
        match self {
            Self::Draft => "DRAFT",
            Self::SubmitWilayah => "SUBMIT_WILAYAH",
            Self::ReturnedToOperator => "RETURNED_TO_OPERATOR",
            Self::SubmitPusat => "SUBMIT_PUSAT",
            Self::VerifikasiPusat => "VERIFIKASI_PUSAT",
            Self::KonsepSKGenerated => "KONSEP_SK_GENERATED",
            Self::SKSigned => "SK_SIGNED",
            Self::Completed => "COMPLETED",
            Self::Rejected => "REJECTED",
            Self::KonsepSKWilayahGenerated => "KONSEP_SK_WILAYAH_GENERATED",
            Self::SKSignedWilayah => "SK_SIGNED_WILAYAH",
        }
    }

    pub fn from_state_name(name: &str) -> Option<Self> {
        match name {
            "DRAFT" => Some(Self::Draft),
            "SUBMIT_WILAYAH" | "SUBMITTED" => Some(Self::SubmitWilayah),
            "RETURNED_TO_OPERATOR" => Some(Self::ReturnedToOperator),
            "SUBMIT_PUSAT" | "REVIEWED" => Some(Self::SubmitPusat),
            "VERIFIKASI_PUSAT" => Some(Self::VerifikasiPusat),
            "KONSEP_SK_GENERATED" => Some(Self::KonsepSKGenerated),
            "SK_SIGNED" | "APPROVED" => Some(Self::SKSigned),
            "COMPLETED" => Some(Self::Completed),
            "REJECTED" => Some(Self::Rejected),
            "KONSEP_SK_WILAYAH_GENERATED" => Some(Self::KonsepSKWilayahGenerated),
            "SK_SIGNED_WILAYAH" => Some(Self::SKSignedWilayah),
            _ => None,
        }
    }

    /// Check if transition to target status is allowed
    ///
    /// Branching SubmitWilayah → KonsepSKWilayahGenerated atau SubmitPusat
    /// hanya satu yg valid per entity berdasarkan `kewenangan_penetap_sk`,
    /// tapi state machine alone tidak punya akses ke entity field — service
    /// layer mem-validate kewenangan match dgn transition target.
    pub fn can_transition_to(&self, target: Self) -> bool {
        use PenghapusanBmnStatus::*;
        match self {
            Draft => matches!(target, SubmitWilayah),
            // V029 (Fase 1.9): jalur kewenangan WILAYAH skip Pusat —
            // langsung KonsepSKWilayahGenerated.
            SubmitWilayah => matches!(
                target,
                SubmitPusat | ReturnedToOperator | KonsepSKWilayahGenerated
            ),
            ReturnedToOperator => matches!(target, SubmitWilayah),
            SubmitPusat => matches!(target, VerifikasiPusat),
            VerifikasiPusat => matches!(target, KonsepSKGenerated | Rejected),
            KonsepSKGenerated => matches!(target, SKSigned),
            SKSigned => matches!(target, Completed),
            // V029: jalur WILAYAH.
            KonsepSKWilayahGenerated => matches!(target, SKSignedWilayah),
            SKSignedWilayah => matches!(target, Completed),
            Completed | Rejected => false,
        }
    }

    pub fn allowed_transitions(&self) -> Vec<Self> {
        use PenghapusanBmnStatus::*;
        match self {
            Draft => vec![SubmitWilayah],
            SubmitWilayah => vec![SubmitPusat, ReturnedToOperator, KonsepSKWilayahGenerated],
            ReturnedToOperator => vec![SubmitWilayah],
            SubmitPusat => vec![VerifikasiPusat],
            VerifikasiPusat => vec![KonsepSKGenerated, Rejected],
            KonsepSKGenerated => vec![SKSigned],
            SKSigned => vec![Completed],
            KonsepSKWilayahGenerated => vec![SKSignedWilayah],
            SKSignedWilayah => vec![Completed],
            Completed | Rejected => vec![],
        }
    }

    /// Normalize a `status` filter string from the API into the canonical
    /// state names stored in the DB (`to_state_name()`).
    ///
    /// Accepts a comma-separated list and legacy/UI aliases (handled by
    /// [`from_state_name`], e.g. `SUBMITTED`→`SUBMIT_WILAYAH`,
    /// `REVIEWED`→`SUBMIT_PUSAT`, `APPROVED`→`SK_SIGNED`). Whitespace is
    /// trimmed, matching is case-insensitive, and unknown tokens are dropped
    /// so a bad value can never silently match every row.
    ///
    /// [`from_state_name`]: PenghapusanBmnStatus::from_state_name
    pub fn normalize_status_filter(raw: &str) -> Vec<String> {
        raw.split(',')
            .map(|s| s.trim())
            .filter(|s| !s.is_empty())
            .filter_map(|s| {
                Self::from_state_name(&s.to_uppercase()).map(|st| st.to_state_name().to_string())
            })
            .collect()
    }
}

